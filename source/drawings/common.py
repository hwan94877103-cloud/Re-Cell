def load():
    parts = T.build()
    qty = {}
    for p in parts:
        qty[p['no']] = qty.get(p['no'], 0) + 1
    item = {no: i + 1 for i, no in enumerate(BOM_INFO)}
    return parts, qty, item


def bom_rows(qty, item):
    rows = []
    for no, (name, mat, kind, spec, dwg) in BOM_INFO.items():
        rows.append([item[no], no, name, qty.get(no, 0), mat, kind, spec, dwg])
    return rows


def plist(nos, qty, item, notes=None):
    """Rows for the exam-style 부품란 on a part drawing sheet."""
    out = []
    for no in nos:
        name, mat, kind, spec, dwg = BOM_INFO[no]
        out.append([item[no], no, name, mat, qty.get(no, 0), (notes or {}).get(no, '')])
    return out


def by_no(parts, no, tag=None):
    out = [p for p in parts if p['no'] == no and (tag is None or p['name'].endswith(tag))]
    return out
