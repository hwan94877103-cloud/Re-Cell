def fmt_tol(up, lo):
    s = lambda v: '0' if abs(v) < 1e-9 else f'{v:+.3f}'.rstrip('0').rstrip('.')
    return f'{s(up)}/{s(lo)}'


def fit_limits(d, hole='H8', shaft='h8'):
    """Hole H / shaft h limits (um) for the grades used here."""
    gh, gs = int(hole[1:]), int(shaft[1:])
    H = (0, it_um(gh, d))
    h = (-it_um(gs, d), 0)
    return dict(hole_um=H, shaft_um=h, clear_min_um=H[0] - h[1], clear_max_um=H[1] - h[0])


