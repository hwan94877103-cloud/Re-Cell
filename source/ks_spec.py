def it_um(grade, size):
    """IT value in um for a nominal size (ranges: over a up to and including b)."""
    for i, b in enumerate(_RANGES):
        if size <= b:
            return IT_TABLE[grade][i]
    raise ValueError(size)


def it_range(size):
    lo = 0
    for b in _RANGES:
        if size <= b:
            return f'{lo}~{b}' if lo else f'~{b}'
        lo = b


